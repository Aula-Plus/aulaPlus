<?php

namespace App\Enums;

use App\Support\AlertRouting;

/**
 * `PlanningAttendance` is a placeholder for when real attendance data exists
 * (docs/prompts/04-seguimiento-institucional.md §4) — the enum case exists,
 * but nothing produces it yet. Comments never open alerts on their own: only
 * the explicit «Señal de dificultad» per category does, through a rule the
 * school configured (`DifficultySignal`).
 */
enum AlertType: string
{
    case Performance = 'performance';
    case PlanningAttendance = 'planning_attendance';

    /**
     * "Alerta escalada con plazo vencido" (ClickUp 86e3jpzdp): generated by
     * `alerts:escalate` when an alert was handed off and its deadline passed
     * without the receiver choosing a way out. It speaks about the circuit
     * (who passed what to whom, and when), never about the student.
     */
    case EscalatedOverdue = 'escalated_overdue';

    /**
     * «Señal de dificultad» (ClickUp 86e3qkwpn): generated by
     * `alerts:difficulty-signals` when a student's observations gather the
     * school-configured number of difficulty signals in one same category
     * within the configured days. It carries only the count and the category
     * — never any observation text, author or id — and never reaches
     * teachers ({@see AlertRouting::allowedRecipients()}).
     */
    case DifficultySignal = 'difficulty_signal';
}
